#!/usr/bin/env python3
"""
Local GPT <-> Cursor bridge for TriGuide-AI.

Reads status docs, calls the OpenAI Chat Completions API, writes
docs/BRIDGE_FROM_GPT.md with a CURSOR_TASK block for Cursor/Grok.

Requires OPENAI_API_KEY in the environment or in a gitignored .env file
at the repo root. Never prints the key.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_MODEL = "gpt-4.1-mini"
API_URL = "https://api.openai.com/v1/chat/completions"

CONTEXT_FILES = [
    "docs/BRIDGE_TO_GPT.md",
    "docs/PROGRESS.md",
    "docs/KNOWN_ISSUES.md",
    "docs/DECISIONS.md",
    "docs/REVIEW_NOTES.md",
    "docs/SAFETY_LIMITATIONS.md",
    "docs/EXTERNAL_GPT_HANDOFF.md",
]


def load_dotenv(path: Path) -> None:
    if not path.is_file():
        return
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        value = value.strip().strip('"').strip("'")
        if key and key not in os.environ:
            os.environ[key] = value


def read_capped(path: Path, max_chars: int) -> str:
    if not path.is_file():
        return f"(missing: {path.as_posix()})"
    text = path.read_text(encoding="utf-8", errors="replace")
    if len(text) <= max_chars:
        return text
    return text[: max_chars - 80] + "\n\n…[truncated for bridge size]…\n"


def build_user_payload(extra: str | None) -> str:
    parts: list[str] = [
        "You are the external GPT planner for TriGuide-AI.",
        "Reply with a short Sudanese-Arabic note for the student, then end with ONE",
        "English block exactly titled ### CURSOR_TASK with Goal, Files, Acceptance,",
        "Safety constraints, Out of scope.",
        "Primary function is path guidance. Consent-only person names. No fake depth.",
        "No fingerprint shortcuts. Floor stays NOT_STARTED unless a real floor model exists.",
        "",
        f"UTC time: {datetime.now(timezone.utc).isoformat()}",
        "",
    ]
    per_file = 12000
    for rel in CONTEXT_FILES:
        path = REPO_ROOT / rel
        parts.append(f"===== FILE: {rel} =====")
        parts.append(read_capped(path, per_file))
        parts.append("")
    if extra:
        parts.append("===== EXTRA NOTE FROM USER =====")
        parts.append(extra)
    return "\n".join(parts)


def call_openai(api_key: str, model: str, user_content: str) -> str:
    body = {
        "model": model,
        "temperature": 0.3,
        "messages": [
            {
                "role": "system",
                "content": (
                    "You plan Android TriGuide work for a Cursor agent. "
                    "Be concrete. Never claim phone tests without evidence in the paste. "
                    "End with ### CURSOR_TASK."
                ),
            },
            {"role": "user", "content": user_content},
        ],
    }
    req = urllib.request.Request(
        API_URL,
        data=json.dumps(body).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as resp:
            payload = json.loads(resp.read().decode("utf-8"))
    except urllib.error.HTTPError as exc:
        detail = exc.read().decode("utf-8", errors="replace")
        raise SystemExit(f"OpenAI HTTP {exc.code}: {detail[:800]}") from exc
    try:
        return payload["choices"][0]["message"]["content"].strip()
    except (KeyError, IndexError, TypeError) as exc:
        raise SystemExit(f"Unexpected OpenAI response: {payload!r}") from exc


def write_bridge(reply: str, model: str) -> Path:
    out = REPO_ROOT / "docs" / "BRIDGE_FROM_GPT.md"
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    header = (
        f"# Bridge: External GPT → Cursor\n\n"
        f"Auto-generated by `scripts/bridge/run_gpt_bridge.py` at {stamp}.\n"
        f"Model: `{model}`.\n\n"
        f"Cursor/Grok: execute the CURSOR_TASK below, then update "
        f"`docs/BRIDGE_TO_GPT.md`.\n\n---\n\n"
    )
    out.write_text(header + reply + "\n", encoding="utf-8")
    return out


def main() -> int:
    parser = argparse.ArgumentParser(description="TriGuide GPT bridge")
    parser.add_argument(
        "--model",
        default=os.environ.get("OPENAI_BRIDGE_MODEL", DEFAULT_MODEL),
        help=f"Chat model (default {DEFAULT_MODEL})",
    )
    parser.add_argument(
        "--note",
        default="",
        help="Optional extra note appended for GPT",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Build the prompt only; do not call the API",
    )
    args = parser.parse_args()

    load_dotenv(REPO_ROOT / ".env")
    api_key = os.environ.get("OPENAI_API_KEY", "").strip()
    user_content = build_user_payload(args.note.strip() or None)

    if args.dry_run:
        preview = REPO_ROOT / "outputs" / "reports" / "gpt-bridge-prompt-preview.txt"
        preview.parent.mkdir(parents=True, exist_ok=True)
        preview.write_text(user_content, encoding="utf-8")
        print(f"DRY RUN: wrote {preview} ({len(user_content)} chars)")
        return 0

    if not api_key:
        print(
            "Missing OPENAI_API_KEY.\n"
            "1) Copy .env.example to .env\n"
            "2) Put your OpenAI API key in OPENAI_API_KEY=...\n"
            "3) Re-run: python scripts/bridge/run_gpt_bridge.py\n"
            "ChatGPT website login alone is not enough — the API key is required "
            "for automatic replies into Cursor.",
            file=sys.stderr,
        )
        return 2

    print(f"Calling OpenAI model={args.model} …")
    reply = call_openai(api_key, args.model, user_content)
    path = write_bridge(reply, args.model)
    print(f"Wrote {path}")
    if "### CURSOR_TASK" not in reply:
        print("WARNING: reply has no ### CURSOR_TASK heading", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
